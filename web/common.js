/* The buildings adjacent to a footprint, one entry per building however many
   of its tiles touch, and never the building itself. Read through the
   occupancy map, since only a multi-tile building's anchor holds its key. */
function buildingsBeside(board, anchor, cells) {
  const occupancy = occupancyMap(board.tiles);
  const anchors = new Set();

  for (const cell of cells) {
    for (const j of neighbours(cell)) {
      if (occupancy[j] !== null && occupancy[j] !== anchor) anchors.add(occupancy[j]);
    }
  }
  return [...anchors].map((one) => board.tiles[one].building);
}

/* --------------------------- describing a tile ---------------------------

   What a building does and what it costs, as the panel beside the board shows
   it. Both pages show the same thing, so it is written once here.

   `board` is what the page has on the board and what the engine last said
   about it: { tiles, result, terrainBonusFactor }. Nothing else is read from
   the page. */

// The resources a level is paid in, in the order the game lists them.
// Soldiers are not spent, so they are excluded.
const COSTED = ['wood', 'iron', 'workers'];
const NO_COST = { wood: 0, iron: 0, workers: 0 };

function anyCost(cost) {
  return COSTED.some((r) => cost[r] > 0);
}

// The cost entry for one building, or for the village. The engine computes
// both and returns them with the rest of the reply.
function costAt(board, anchor) {
  const cost = board.result?.cost;
  if (!cost || anchor === null) return null;
  if (board.tiles[anchor].building === CENTRE) return cost.village;
  return cost.buildings.find((one) => one.tile === anchor) ?? null;
}

/* Every effect a building has in the selected game, whether or not it applies
   on this tile. These are the effects the engine computes from, so the panel
   and the arithmetic cannot diverge.

   Ordered as the game presents them: what the building does unconditionally,
   then one block per terrain it responds to, then what its neighbours
   contribute; blocks that do not currently apply are shown greyed. */




const QUANTITY_NAMES = {
  wood: 'Wood', iron: 'Iron', workers: 'Workers', soldiers: 'Soldiers',
  knight: 'Knight', guardian: 'Guardian', market_order: 'Market orders',
  build_order: 'Build orders', attack: 'Attack', defense: 'Defense',
  market_tax: 'Market tax',
  knightPower: 'Knight power', guardianPower: 'Guardian power',
  map_efficiency: 'Map efficiency', worker_project_efficiency: 'Project efficiency',
  recycling: 'Recycling', specialization: 'Specialisation',
};

// Quantities the engine carries through to the totals. The rest are displayed
// and labelled as uncounted rather than silently dropped.
const COUNTED = new Set(['wood', 'iron', 'workers', 'soldiers', 'knight', 'guardian',
  'attack', 'defense', 'map_efficiency', 'worker_project_efficiency',
  'knightPower', 'guardianPower', 'market_tax', 'efficiency']);

// Quantities the Makes and Holds blocks already total, so Total skips them.
const COUNTED_IN_OUTPUT = new Set(['wood', 'iron', 'workers', 'soldiers', 'efficiency']);

const QUANTITY_CLASS = {
  wood: 'wood-value', iron: 'iron-value', workers: 'workers-value', soldiers: 'soldiers-value',
};

/* An `efficiency` effect names no resource: it multiplies whatever its targets
   produce or store. Where every target produces exactly one quantity on that
   side, the label names it, so a sawmill reads "Wood production" rather than an
   unqualified boost. An arena targets barracks producing soldiers and mercenary
   offices producing two quantities, so it stays a boost. */
const BOOST_NAMES = { both: 'Output boost', production: 'Production boost', storage: 'Storage boost' };

function onlyQuantityBoosted(effect) {
  if (effect.on.length === 0) return null;

  const found = new Set();
  for (const target of effect.on) {
    for (const its of effectsByBuilding.get(target) ?? []) {
      if (its.where !== 'base' && its.where !== 'terrain') continue;
      if (its.quantity === 'efficiency' || its.rateOrCapacity !== effect.rateOrCapacity) continue;
      found.add(its.quantity);
    }
  }
  return found.size === 1 ? [...found][0] : null;
}

// World-map ratings, which are neither production nor storage.
const WORLD_RATINGS = new Set(['attack', 'defense', 'knightPower', 'guardianPower',
  'map_efficiency', 'worker_project_efficiency']);

// The two of those that are a power rather than an efficiency: their names
// already say what they are, so nothing is appended to them.
const WORLD_POWERS = new Set(['knightPower', 'guardianPower']);

function effectLabel(effect) {
  if (WORLD_RATINGS.has(effect.quantity)) {
    const rating = QUANTITY_NAMES[effect.quantity] ?? effect.quantity;
    return WORLD_POWERS.has(effect.quantity) ? rating : `${rating} efficiency`;
  }
  if (effect.quantity === 'efficiency') {
    const only = onlyQuantityBoosted(effect);
    if (only !== null) return `${QUANTITY_NAMES[only] ?? only} ${effect.rateOrCapacity}`;
    return BOOST_NAMES[effect.rateOrCapacity] ?? 'Output boost';
  }

  const named = QUANTITY_NAMES[effect.quantity] ?? effect.quantity;
  if (effect.rateOrCapacity === 'both' || effect.quantity === 'market_tax') return named;
  return `${named} ${effect.rateOrCapacity}`;
}

// The same wording for an aura read off the reply, which names its source but
// not what that source targets.
function auraLabel(board, from, rateOrCapacity) {
  const provided = (effectsByBuilding.get(from) ?? []).find(
    (e) => e.where === 'provides' && e.rateOrCapacity === rateOrCapacity,
  );
  return provided === undefined
    ? BOOST_NAMES[rateOrCapacity] ?? 'Output boost'
    : effectLabel(provided);
}

/* Which seal multiplies a rate and which a capacity. A quantity that names
   neither is treated as a rate, as the engine's resolveRateOrCapacity does. */
const SEAL_FOR_RATE_OR_CAPACITY = { production: 'ECONOMIC_BOOST', storage: 'STORAGE_EXPANDER', both: 'ECONOMIC_BOOST' };

/* Whether the seal on this tile multiplies what this row contributes.

   A mill multiplies what a tile produces and a barrel what it stores, so
   neither applies to an aura, a rating or the tax: none of those is a resource
   of this tile. Where the building has a base of its own, the seal multiplies
   that base, which the flat row already carries, so the shares and factors
   over it are left alone rather than counted twice. Where it has none, its
   village-wide contribution passes through the seal, except a share that does
   not scale with level: that one is village-wide outright (see effects.cpp). */
function sealScales(effect, seal, effects) {
  if (seal !== SEAL_FOR_RATE_OR_CAPACITY[effect.rateOrCapacity]) return false;
  if (!GLOBAL_RESOURCES.includes(effect.quantity) || effect.where === 'provides') return false;
  if (hasBaseOfItsOwn(effect, effects)) return effect.amount === 'flat';
  return effect.amount !== 'share' || effect.perLevel;
}

/* Whether the building has a base of its own for the shares and factors to
   multiply, from any source: a house stores soldiers only when adjacent to a
   guard tower, and that is still its own quantity rather than the village's. */
function hasBaseOfItsOwn(effect, effects) {
  return effects.some((its) => its.amount === 'flat'
    && its.quantity === effect.quantity && its.rateOrCapacity === effect.rateOrCapacity);
}

/* A master builder's seal multiplies the level that per-level effects scale
   by; a mill or a barrel multiplies the quantity itself. A factor accumulates
   the way the game writes it: 1.05 per level at level 39 is 1 + 0.05 * 39 =
   x2.95, not 1.05^39. */
function effectTimes(effect, level, seal, over = 1, effects = []) {
  return over
    * (effect.perLevel ? level * (seal === 'LEVEL_BOOST' ? MASTER_LEVEL_BONUS : 1) : 1)
    * (sealScales(effect, seal, effects) ? SEAL_BONUS : 1);
}

function effectAmount(effect, level, seal, over = 1, effects = []) {
  const times = effectTimes(effect, level, seal, over, effects);

  if (effect.amount === 'multiply') return `×${fmt(1 + (effect.value - 1) * times, 2)}`;
  if (effect.amount === 'share') return `+${fmt(effect.value * 100 * times, 1)}%`;

  const value = effect.value * times;
  if (effect.quantity === 'market_tax') return `${fmt(value * 100, 1)}%`;
  const shown = Math.abs(value) >= 1000 ? fmtStore(value) : fmt(value, 2);
  return value < 0 ? shown : `+${shown}`;
}

/* A share with no base of the building's own applies to the village instead.
   Shares that do not scale with level are village-wide outright: a furnace on
   plains contributes its ten percent regardless of its neighbours, its seal
   and its level, so they are marked and excluded from the building's own
   total. Shares that scale with level are not marked and do count towards it. */
function ownFigureFor(effect, effects) {
  return effects.some((its) => its.amount === 'flat'
    && its.quantity === effect.quantity && its.rateOrCapacity === effect.rateOrCapacity
    && (its.where === 'base' || its.where === 'terrain'));
}

function goesToWholeVillage(effect, effects) {
  return effect.amount !== 'flat' && !effect.perLevel
    && (effect.where === 'base' || effect.where === 'terrain')
    && !ownFigureFor(effect, effects);
}

function effectRow(effect, level, seal, from = '', times = 1, dim = false, effects = [], explains = '') {
  const notes = (COUNTED.has(effect.quantity) ? '' : '<span class="fx-note">not counted</span>')
    + (effect.perLevel ? '<span class="fx-note" title="Scales with the building\'s level">&uarr;lvl</span>' : '')
    + (goesToWholeVillage(effect, effects)
      ? '<span class="fx-note fx-global" title="Worth this to the whole village, not to this tile">global</span>'
      : '');

  // A factor is rendered green, a share or a flat amount white.
  const kind = effect.amount === 'multiply' ? 'fx-times' : 'fx-plus';

  return `<li${dim ? ' class="fx-dim"' : ''}><span class="fx-what">${effectLabel(effect)}</span>`
    + `<span class="fx-value ${kind}${explains === '' ? '' : ' fx-explained'}" ${explains}>`
    + `${effectAmount(effect, level, seal, times, effects)}</span>${notes}`
    + (from === '' ? '' : `<span class="fx-from">${from}</span>`)
    + '</li>';
}

function effectBlock(title, kind, live, rows) {
  if (rows.length === 0) return '';
  return `<h4 class="fx-head fx-${kind}${live ? '' : ' fx-dim'}">${title}</h4>`
    + `<ul class="fx-list fx-${kind}${live ? '' : ' fx-dim'}">${rows.join('')}</ul>`;
}

/* What the engine scales a terrain effect by over the tiles a building
   covers: one per matching tile, terrainBonusFactor where terraformed. */
function terrainScale(board, cells, ground) {
  const factor = board.terrainBonusFactor ?? 1;
  let scale = 0;

  for (const cell of cells) {
    if (board.tiles[cell].terrain !== ground) continue;
    scale += board.tiles[cell].terraformed === true ? factor : 1;
  }
  return scale;
}

// The auras reaching a tile, as rows for the adjacency block: the factor and
// the neighbour providing it.
function aurasOn(board, anchor, cells) {
  if (!board.result) return [];

  const { modifiers } = board.result;
  const twice = new Set(modifiers
    .map((m) => m.from)
    .filter((from, at, all) => all.indexOf(from) !== at));

  const beside = buildingsBeside(board, anchor, cells);

  return modifiers
    .filter((m) => cells.some((cell) => m.values[cell] !== 0))
    .map((m) => {
      const named = BUILDING_BY_KEY.get(m.from)?.name ?? m.from;
      const count = beside.filter((b) => b === m.from).length;
      const reaching = cells.reduce((sum, cell) => sum + m.values[cell], 0);
      const from = twice.has(m.from) ? `${named} (${m.rateOrCapacity})` : named;

      return `<li><span class="fx-what">${auraLabel(board, m.from, m.rateOrCapacity)}</span>`
        + `<span class="fx-value">×${fmt(1 + reaching, 2)}</span>`
        + `<span class="fx-from">${count > 1 ? `${from} ×${count}` : from}</span></li>`;
    });
}

/* The auras reaching a tile that multiply one quantity, as
   Rules::aurasThatMultiply picks them: over efficiency multiplies every
   quantity, one named for a quantity that one alone, one over both a rate and
   a capacity alike. A building covering several tiles is reached once. */
function aurasMultiplying(board, cells, quantity, rateOrCapacity) {
  if (!board.result) return [];

  return board.result.modifiers
    .filter((aura) => aura.quantity === SCHEMA.efficiencyField || aura.quantity === quantity)
    .filter((aura) => aura.rateOrCapacity === 'both' || aura.rateOrCapacity === rateOrCapacity)
    .map((aura) => ({ from: aura.from, value: 1 + cells.reduce((sum, cell) => sum + aura.values[cell], 0) }))
    .filter((aura) => aura.value !== 1);
}

/* What one building accumulates, from the same rules the rows above are drawn
   from. Shares and factors are summed and multiplied separately, since shares
   add into the sum and factors multiply it. Flat shares are excluded, being
   village-wide rather than this building's.

   Where the building has no base of its own, what it contributes goes to the
   village and the auras reaching this tile multiply it, exactly as they
   multiply the output of a building that has one. Where it has a base, that
   base is what they multiply, and the tile's own figure already carries them,
   so counting them here as well would count them twice.

   Attack, defense and the tax also pass through here: the engine counts them
   into no resource, so it reports no per-tile value for them. */
function effectTotals(board, anchor, level) {
  const tile = board.tiles[anchor];
  const effects = effectsByBuilding.get(tile.building) ?? [];
  const cells = footprintCells(anchor, tile.building, tile.orientation) ?? [anchor];
  const beside = buildingsBeside(board, anchor, cells);

  const totals = new Map();
  for (const effect of effects) {
    const times = effectReach(board, cells, beside, effect);
    if (times === 0 || goesToWholeVillage(effect, effects)) continue;

    const key = `${effect.quantity}|${effect.rateOrCapacity}`;
    const running = totals.get(key) ?? {
      quantity: effect.quantity,
      rateOrCapacity: effect.rateOrCapacity,
      // a per-level share is multiplied by the auras; a flat one is village-wide outright
      perLevelShare: 0,
      flatShare: 0,
      factor: 1,
      counted: 0,
      from: [],
      toVillage: !hasBaseOfItsOwn(effect, effects),
    };

    const scaled = effectTimes(effect, level, tile.seal, times, effects);
    if (effect.amount === 'share') {
      if (effect.perLevel) running.perLevelShare += effect.value * scaled;
      else running.flatShare += effect.value * scaled;
    } else if (effect.amount === 'multiply') {
      running.factor *= 1 + (effect.value - 1) * scaled;
    }
    running.counted += 1;
    running.from.push({ effect, times, ground: effectGround(board, cells, effect) });

    totals.set(key, running);
  }

  const finished = [...totals.values()].map((one) => {
    const auras = one.toVillage ? aurasMultiplying(board, cells, one.quantity, one.rateOrCapacity) : [];
    const reaching = auras.reduce((product, aura) => product * aura.value, 1);

    return {
      ...one,
      auras,
      // What the building came to before any aura reached it, kept so the
      // panel can show the two apart.
      ownFactor: one.factor,
      share: one.perLevelShare * reaching + one.flatShare,
      // A factor is stored as the factor and contributed as what it adds, so
      // the auras multiply the amount above one rather than the factor.
      factor: 1 + (one.factor - 1) * reaching,
    };
  });

  /* A building with a figure of its own has it reported per tile, with these
     shares and factors already counted into it, so repeating them here would
     state them twice. What goes to the village has no such figure, and nor do
     the quantities the engine counts into no resource: a rating or the tax is
     reported for the village alone, so its row is the only place it shows.

     Rows carrying a share come first, as the game orders them. */
  return finished
    .filter((one) => one.share !== 0 || one.factor !== 1)
    .filter((one) => one.toVillage || !GLOBAL_RESOURCES.includes(one.quantity))
    .sort((a, b) => (b.share !== 0) - (a.share !== 0));
}

/* Shares and factors get a column each, so the values align down the block
   instead of following the label. A block with no factors needs one column.

   Each figure carries what it would take to explain it, so that clicking it
   opens the same panel the stats panel uses. */
function totalRow(one, withFactors, anchor) {
  const share = one.share === 0 ? ''
    : `${one.share > 0 ? '+' : ''}${fmt(one.share * 100, 1)}%`;
  const explains = `data-tile-total="${anchor}|${one.quantity}|${one.rateOrCapacity}"`;

  return `<li><span class="fx-what">${effectLabel(one)}</span>`
    + `<span class="fx-value fx-plus${share === '' ? '' : ' fx-explained'}" ${share === '' ? '' : explains}>${share}</span>`
    + (withFactors
      ? `<span class="fx-value fx-times${one.factor === 1 ? '' : ' fx-explained'}" ${one.factor === 1 ? '' : explains}>${one.factor === 1 ? '' : `×${fmt(one.factor, 2)}`}</span>`
      : '')
    + '</li>';
}

function buildingEffects(board, anchor, level, auraRows = []) {
  const tile = board.tiles[anchor];
  const effects = effectsByBuilding.get(tile.building) ?? [];
  if (effects.length === 0) return '';

  const cells = footprintCells(anchor, tile.building, tile.orientation) ?? [anchor];
  const standing = new Set(cells.map((cell) => board.tiles[cell].terrain));
  const beside = buildingsBeside(board, anchor, cells);

  let html = effectBlock('Effects', 'base', true,
    effects.filter((e) => e.where === 'base')
      .map((e) => effectRow(e, level, tile.seal, '', 1, false, effects)));

  /* One block per terrain this building responds to, applying or not. A
     terrain it does not stand on is shown at what one matching tile would be
     worth: the block is already greyed, so the figure says what moving the
     building would gain. The adjacency rows below read the same way. */
  const grounds = [...new Set(effects.filter((e) => e.where === 'terrain').flatMap((e) => e.on))];
  for (const ground of grounds) {
    const matching = cells.filter((cell) => board.tiles[cell].terrain === ground).length;
    const scale = terrainScale(board, cells, ground);
    const rows = effects
      .filter((e) => e.where === 'terrain' && e.on.includes(ground))
      .map((e) => effectRow(e, level, tile.seal, '', Math.max(scale, 1), false, effects));
    const named = TERRAIN_BY_KEY.get(ground)?.name ?? ground;
    const live = standing.has(ground);
    /* Covered tiles of this terrain, which says something only over several
       tiles with some matching: on one tile it repeats the name, and where
       none match the cross has said so. */
    const counted = cells.length > 1 && matching > 0 ? ` ${matching}/${cells.length}` : '';
    // the rows above already carry it; this names it
    const fertile = scale > matching
      ? `<li class="fx-fertile">+ ${FERTILE_GROUNDS} +${fmt((board.terrainBonusFactor - 1) * 100, 2)}%</li>`
      : '';
    html += effectBlock(`${live ? named : `✗ ${named}`}${counted}`, 'terrain', live,
      rows.length === 0 ? rows : [...rows, fertile]);
  }

  /* One row per building an adjacency effect names, worth its value times the
     number of them adjacent. A target with none adjacent is still shown,
     greyed and at its single-neighbour value, so the requirement is visible. */
  const fromNeighbours = effects.filter((e) => e.where === 'adjacent');
  const wanted = [...new Set(fromNeighbours.flatMap((e) => e.on))];

  const adjacent = [];
  for (const want of wanted) {
    const count = beside.filter((b) => b === want).length;
    const named = BUILDING_BY_KEY.get(want)?.name ?? want;

    for (const effect of fromNeighbours.filter((e) => e.on.includes(want))) {
      adjacent.push({
        row: effectRow(effect, level, tile.seal, count > 1 ? `${named} ×${count}` : named,
          Math.max(count, 1), count === 0, effects),
        live: count > 0,
      });
    }
  }

  const adjacencyRows = adjacent.map((a) => a.row).concat(auraRows);
  if (adjacencyRows.length > 0) {
    html += effectBlock('Adjacency bonus', 'adj',
      adjacent.some((a) => a.live) || auraRows.length > 0, adjacencyRows);
  }

  /* What this building gives its neighbours, at what the engine wrote to
     their tiles: the auras reaching this tile do not scale it. */
  const gives = effects.filter((e) => e.where === 'provides').map((e, n) => {
    const reaches = e.on.length === 0
      ? 'every neighbour'
      : `adjacent ${e.on.map((want) => (e.byCategory
        ? `${want.toLowerCase()} buildings`
        : (BUILDING_BY_KEY.get(want)?.name ?? want).toLowerCase())).join(', ')}`;

    return effectRow(e, level, tile.seal, '', 1, false, effects,
      `data-tile-aura="${anchor}|${n}"`)
      .replace('</li>', `<span class="fx-reaches">to ${reaches}</span></li>`);
  });
  html += effectBlock('Aura', 'gives', true, gives);


  return html;
}

/* What this building has cost so far and what its next level costs, side by
   side. Both come from the engine, priced against the selected round. */
function costBlock(board, anchor) {
  const cost = costAt(board, anchor);
  if (cost === null) return '';

  const village = board.tiles[anchor].building === CENTRE;
  const rows = COSTED
    .filter((resource) => cost.next[resource] > 0 || cost.spent[resource] > 0)
    .map((resource) => `<li><span class="fx-what">${resource}</span>`
      + `<span class="fx-value ${resource}-value">`
      + `${cost.next[resource] > 0 ? fmtStore(cost.next[resource]) : '—'}</span>`
      + `<span class="fx-value">`
      + `${cost.spent[resource] > 0 ? fmtStore(cost.spent[resource]) : '—'}</span></li>`);
  if (rows.length === 0) return '';

  const next = anyCost(cost.next) ? `to lvl ${cost.level + 1}` : 'at its highest';
  const columns = '<li class="fx-cols"><span class="fx-what"></span>'
    + `<span class="fx-value" title="What the next level costs">${next}</span>`
    + `<span class="fx-value" title="Everything paid to reach level ${cost.level}">spent</span></li>`;

  return effectBlock(village ? 'Village levels' : 'Cost', 'cost', true, [columns, ...rows]);
}

/* The whole detail pane for one tile: what the building standing there does,
   what the tile comes to, and what it cost. `anchor` is the tile the building
   is stored on, which is `i` itself for bare ground and for a single tile. */
function tileDetail(board, i, anchor) {
  lastBoard = board;
  const owner = anchor === null ? null : board.tiles[anchor];

  let html = '';
  if (owner !== null) {
    html += buildingEffects(board, anchor, owner.level,
      aurasOn(board, anchor, footprintCells(anchor, owner.building, owner.orientation) ?? [anchor]));
  }

  /* The tile's totals, counting everything above: the resources the engine
     computed, then the ratings it carries but does not count. */
  const totals = [];
  if (board.result) {
    const { tiles } = board.result;
    const src = anchor === null ? i : anchor;

    // Each figure carries its breakdown id and tile, so a click narrows to this tile.
    const line = (name, value, cls, id) => `<li><span class="fx-what">${name}</span>`
      + `<span class="fx-value ${cls} fx-explained" data-breakdown="${id}" data-tile="${src}">${value}</span></li>`;

    for (const r of RESOURCES) {
      if (tiles.production[r.key][src] > 0) {
        totals.push(line(`${r.name} production`, `+${fmt(tiles.production[r.key][src], 3)}`, r.cls, `${r.key}.production`));
      }
    }
    for (const r of RESOURCES) {
      if (tiles.storage[r.key][src] > 0) {
        totals.push(line(`${r.name} storage`, `+${fmtStore(tiles.storage[r.key][src])}`, r.cls, `${r.key}.storage`));
      }
    }
  }

  if (owner !== null) {
    const gathered = effectTotals(board, anchor, owner.level);
    const withFactors = gathered.some((one) => one.factor !== 1);
    totals.push(...gathered.map((one) => totalRow(one, withFactors, anchor)));
  }

  html += effectBlock('Total', 'out', true, totals);
  if (owner !== null) html += costBlock(board, anchor);
  return html;
}

