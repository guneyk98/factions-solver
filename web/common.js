// Merges an engine-supplied row with this file's presentation fields, engine
// first, so nothing here can override a computed value.
function joined(rows, trimmings, what) {
  const listed = rows.map((row) => (typeof row === 'string' ? { id: row } : row));

  const bare = listed.filter((row) => !(row.id in trimmings)).map((row) => row.id);
  if (bare.length) throw new Error(`app.js has no ${what} for: ${bare.join(', ')}`);

  const extra = Object.keys(trimmings).filter((id) => !listed.some((row) => row.id === id));
  if (extra.length) throw new Error(`app.js describes ${what} the engine has never heard of: ${extra.join(', ')}`);

  return listed.map(({ id, ...engine }) => ({ key: id, ...engine, ...trimmings[id] }));
}

