// A game's flat terrain list reshaped into rows, for indexing by x and y.
function terrainRows(game) {
  const rows = [];
  for (let y = 0; y < game.height; y += 1) {
    rows.push(game.terrain.slice(y * game.width, (y + 1) * game.width));
  }
  return rows;
}

