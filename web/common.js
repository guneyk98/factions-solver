function atlasPosition(index) {
  const col = index % ATLAS_COLS;
  const row = Math.floor(index / ATLAS_COLS);
  const x = (ATLAS_PAD + col * ATLAS_CELL) / (ATLAS_W - ATLAS_ART) * 100;
  const y = (ATLAS_PAD + row * ATLAS_CELL) / (ATLAS_H - ATLAS_ART) * 100;
  return `${x}% ${y}%`;
}

function terrainMask(tiles, i) {
  const x = i % WIDTH;
  const y = Math.floor(i / WIDTH);
  const here = tiles[i].terrain;

  const same = (dx, dy) => {
    const cx = x + dx;
    const cy = y + dy;
    if (cx < 0 || cx >= WIDTH || cy < 0 || cy >= HEIGHT) return false;
    return tiles[cy * WIDTH + cx].terrain === here;
  };

  const n = same(0, -1);
  const e = same(1, 0);
  const s = same(0, 1);
  const w = same(-1, 0);

  let mask = 0;
  if (n) mask |= 1;
  if (e) mask |= 4;
  if (s) mask |= 16;
  if (w) mask |= 64;
  if (n && e && same(1, -1)) mask |= 2;
  if (e && s && same(1, 1)) mask |= 8;
  if (s && w && same(-1, 1)) mask |= 32;
  if (w && n && same(-1, -1)) mask |= 128;
  return mask;
}

function applyTerrain(el, key, mask) {
  const terrain = TERRAIN_BY_KEY.get(key);
  el.style.backgroundColor = terrain.color; // shows through until the sheet loads

  if (terrain.atlas === null) {
    el.style.setProperty('--terrain-img', 'NONE');
    el.style.setProperty('--terrain-pos', '0 0');
    return;
  }

  const local = MASK_TO_LOCAL[mask] ?? 0;
  el.style.setProperty('--terrain-img', `url("${TERRAIN_ATLAS}")`);
  el.style.setProperty('--terrain-pos', atlasPosition(terrain.atlas + local));
}

