// What an exception has to say, whether or not it is an Error.
function reason(err) {
  return String(err?.message ?? err);
}

function plural(n, word) {
  return `${n} ${word}${n === 1 ? '' : 's'}`;
}

// A cell's index, or null if the coordinates fall outside the grid.
function cellAt(x, y) {
  return x >= 0 && x < WIDTH && y >= 0 && y < HEIGHT ? index(x, y) : null;
}

/* The offsets of a shape's cells from its anchor, which is always [0, 0] and
   comes first; grid edges are not considered. Mirrors footprintOf in
   village.cpp: Line is the anchor plus the tile east or south of it; Square is
   a fixed 2x2 block right of and below the anchor; LShape is the anchor (the
   corner tile) plus the pair of arms the orientation selects. */
function footprintOffsets(key, orientation) {
  const shape = shapeOf(key);
  if (shape === 'single') return [[0, 0]];
  if (shape === 'line') return [[0, 0], orientation === SOUTH ? [0, 1] : [1, 0]];
  if (shape === 'square') return [[0, 0], [1, 0], [0, 1], [1, 1]];

  const arms = {
    [EAST]: [[1, 0], [0, 1]],
    [SOUTH]: [[0, 1], [-1, 0]],
    [WEST]: [[-1, 0], [0, -1]],
    [NORTH]: [[0, -1], [1, 0]],
  }[orientation] ?? [[1, 0], [0, 1]];
  return [[0, 0], ...arms];
}

// The cells a shape covers when anchored at i, or null if any falls outside
// the grid.
function footprintCells(i, key, orientation) {
  const x = i % WIDTH;
  const y = Math.floor(i / WIDTH);
  const cells = footprintOffsets(key, orientation).map(([dx, dy]) => cellAt(x + dx, y + dy));
  return cells.some((c) => c === null) ? null : cells;
}

/* The tile the level badge is drawn on: the southernmost cell, and the
   easternmost of those. Indices run row by row, so that is their maximum. */
function levelCell(tiles, anchor) {
  const tile = tiles[anchor];
  const cells = footprintCells(anchor, tile.building, tile.orientation);
  return cells === null ? anchor : Math.max(...cells);
}

// tile index -> anchor index of the building covering it, or null.
function occupancyMap(tiles) {
  const map = new Array(TILE_COUNT).fill(null);
  for (let i = 0; i < TILE_COUNT; i += 1) {
    const tile = tiles[i];
    if (tile.building === EMPTY) continue;
    const cells = footprintCells(i, tile.building, tile.orientation) ?? [i];
    for (const cell of cells) map[cell] = i;
  }
  return map;
}

// The next orientation while placing or dragging: a Line alternates East and
// South; an LShape advances one quarter-turn clockwise.
function rotate(key, orientation) {
  if (shapeOf(key) === 'line') return orientation === SOUTH ? EAST : SOUTH;
  return { [EAST]: SOUTH, [SOUTH]: WEST, [WEST]: NORTH, [NORTH]: EAST }[orientation] ?? EAST;
}

// Whether the building covers more than one cell, which decides collision,
// stranding and the spanning icon, independently of whether it can be turned.
function isMultiTile(key) {
  return shapeOf(key) !== 'single';
}

// Whether the rotate control does anything: a Square is identical in every
// orientation.
function isRotatable(key) {
  const shape = shapeOf(key);
  return shape === 'line' || shape === 'l';
}

function fmt(value, digits = 2) {
  if (!Number.isFinite(value)) return '0';
  return String(Number(value.toFixed(digits)));
}

function pct(value) {
  return `${value >= 0 ? '+' : ''}${fmt(value * 100, 1)}%`;
}

function fmtStore(value) {
  if (!Number.isFinite(value)) return '0';
  return Math.round(value).toLocaleString('en-US');
}

function fmtStoreShort(value) {
  if (!Number.isFinite(value)) return '0';
  if (value < 1000) return String(Math.round(value));
  return `${fmt(value / 1000, value < 10000 ? 1 : 0)}k`;
}

function readEffects(id) {
  const game = GAME_BY_ID.get(id) ?? GAMES[0];
  effectsByBuilding = new Map();
  for (const effect of game.effects) {
    if (!effectsByBuilding.has(effect.building)) effectsByBuilding.set(effect.building, []);
    effectsByBuilding.get(effect.building).push(effect);
  }

  // Shape is per game too: a building can occupy one tile in one round and
  // three in the next.
  shapeByBuilding = new Map(game.shapes.map((s) => [s.building, s.shape]));
}

function shapeOf(key) {
  return shapeByBuilding.get(key) ?? 'single';
}

function neighbours(i) {
  const x = i % WIDTH;
  const y = Math.floor(i / WIDTH);
  const out = [];
  if (x > 0) out.push(i - 1);
  if (x + 1 < WIDTH) out.push(i + 1);
  if (y > 0) out.push(i - WIDTH);
  if (y + 1 < HEIGHT) out.push(i + WIDTH);
  return out;
}

function attachEngine(module) {
  const call = (name, ...args) => {
    const pointers = args.map((text) => module.stringToNewUTF8(text));
    const out = module.ccall(name, 'number', args.map(() => 'number'), pointers);
    for (const pointer of pointers) module._free(pointer);

    const answer = module.UTF8ToString(out);
    module._apiFree(out);

    // WebAssembly cannot propagate an exception across the boundary, so a
    // rejection is returned as text prefixed with '!'. See src/wasm.cpp.
    if (answer.startsWith('!')) throw new Error(answer.slice(1));
    return answer;
  };

  return {
    parse: (body) => call('apiParse', body),
    production: (body) => call('apiProduction', body),
    rearrange: (body, goal, effort) => call('apiRearrange', body, goal, effort),
    simulate: (script) => call('apiSimulate', script),
  };
}

/* ---------------------------- export and import ---------------------------

   A layout or a run travels as base64 of a small JSON envelope, so that what
   is pasted about is one unbroken token rather than something a chat client
   will reflow. */

function toBase64(text) {
  const bytes = new TextEncoder().encode(text);
  let binary = '';
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary);
}

function fromBase64(text) {
  const binary = atob(text.replace(/\s+/g, ''));
  return new TextDecoder().decode(Uint8Array.from(binary, (c) => c.charCodeAt(0)));
}

